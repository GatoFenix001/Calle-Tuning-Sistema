-- 1. Roles
CREATE TABLE public.rol (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL UNIQUE
);

-- 2. Usuarios
CREATE TABLE public.usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    apellido VARCHAR(100) NOT NULL,
    estado BOOLEAN NOT NULL DEFAULT TRUE,
    nombre VARCHAR(100) NOT NULL,
    password VARCHAR(255) NOT NULL,
    username VARCHAR(50) NOT NULL UNIQUE,
    rol_id BIGINT NOT NULL,
    CONSTRAINT fk_usuario_rol FOREIGN KEY (rol_id)
        REFERENCES public.rol(id)
);

-- 3. Categorías
CREATE TABLE public.categoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion VARCHAR(255),
    nombre VARCHAR(100) NOT NULL UNIQUE
);

-- 4. Marcas
CREATE TABLE public.marca (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE
);

-- 5. Proveedores
CREATE TABLE public.proveedor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    direccion VARCHAR(255),
    email VARCHAR(100),
    nombre VARCHAR(150) NOT NULL,
    telefono VARCHAR(20)
);

-- 6. Clientes
CREATE TABLE public.cliente (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    apellido VARCHAR(100) NOT NULL,
    documento VARCHAR(20) NOT NULL UNIQUE,
    email VARCHAR(100),
    nombre VARCHAR(100) NOT NULL,
    telefono VARCHAR(20)
);

-- 7. Productos
CREATE TABLE public.producto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion VARCHAR(255),
    estado BOOLEAN NOT NULL DEFAULT TRUE,
    nombre VARCHAR(150) NOT NULL,
    precio NUMERIC(10,2) NOT NULL CHECK (precio >= 0),
    stock INTEGER NOT NULL DEFAULT 0 CHECK (stock >= 0),
    stock_minimo INTEGER NOT NULL DEFAULT 0 CHECK (stock_minimo >= 0),
    categoria_id BIGINT NOT NULL,
    marca_id BIGINT NOT NULL,
    proveedor_id BIGINT NOT NULL,
    CONSTRAINT fk_producto_categoria FOREIGN KEY (categoria_id)
        REFERENCES public.categoria(id),
    CONSTRAINT fk_producto_marca FOREIGN KEY (marca_id)
        REFERENCES public.marca(id),
    CONSTRAINT fk_producto_proveedor FOREIGN KEY (proveedor_id)
        REFERENCES public.proveedor(id)
);

-- 8. Ventas
CREATE TABLE public.venta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    total NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (total >= 0),
    cliente_id BIGINT NOT NULL,
    usuario_id BIGINT NOT NULL,
    CONSTRAINT fk_venta_cliente FOREIGN KEY (cliente_id)
        REFERENCES public.cliente(id),
    CONSTRAINT fk_venta_usuario FOREIGN KEY (usuario_id)
        REFERENCES public.usuario(id)
);

-- 9. Detalle de ventas
CREATE TABLE public.detalle_venta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cantidad INTEGER NOT NULL CHECK (cantidad > 0),
    precio_unitario NUMERIC(10,2) NOT NULL CHECK (precio_unitario >= 0),
    subtotal NUMERIC(10,2) NOT NULL CHECK (subtotal >= 0),
    producto_id BIGINT NOT NULL,
    venta_id BIGINT NOT NULL,
    CONSTRAINT fk_detalle_producto FOREIGN KEY (producto_id)
        REFERENCES public.producto(id),
    CONSTRAINT fk_detalle_venta FOREIGN KEY (venta_id)
        REFERENCES public.venta(id)
);

-- 10. Movimientos de inventario
CREATE TABLE public.movimiento_inventario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cantidad INTEGER NOT NULL CHECK (cantidad > 0),
    fecha TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    motivo VARCHAR(255),
    tipo_movimiento VARCHAR(20) NOT NULL
        CHECK (tipo_movimiento IN ('ENTRADA', 'SALIDA', 'AJUSTE')),
    producto_id BIGINT NOT NULL,
    usuario_id BIGINT NOT NULL,
    CONSTRAINT fk_movimiento_producto FOREIGN KEY (producto_id)
        REFERENCES public.producto(id),
    CONSTRAINT fk_movimiento_usuario FOREIGN KEY (usuario_id)
        REFERENCES public.usuario(id)
);

