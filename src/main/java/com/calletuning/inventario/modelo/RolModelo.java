package com.calletuning.inventario.modelo;

public class RolModelo {

    private Long id;
    private String nombre;

    public RolModelo() {
    }

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public String getNombre() {
        return nombre;
    }

    public void setNombre(String nombre) {
        this.nombre = nombre;
    }
}